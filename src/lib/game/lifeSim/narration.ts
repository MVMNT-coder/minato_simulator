// 年代ごとの社会背景(硬質)。20歳=2046年、以降+20年。
const YEAR_BY_AGE: Record<LifeAge, number> = {
  20: 2046,
  40: 2066,
  60: 2086,
  100: 2126,
};

const BACKGROUND_BY_AGE: Record<LifeAge, string> = {
  20: "2046年。気候と経済の不確実性を抑えるため、社会は「人生の設計」を制度に委ねはじめた。若者の多くは、進路をアルゴリズムに相談する。",
  40: "2066年。制度は生活のすみずみに入り込んだ。人々は制度の恩恵を当たり前に享受し、その外側を想像しにくくなっている。",
  60: "2086年。寿命は延び、社会は「長く生きること」の意味を問い直しはじめた。高齢期のあり方そのものが、制度の対象になった。",
  100: "2126年。百歳を超える市民は珍しくない。生と死の境界すら選択できるようになった社会は、最も長く生きた者たちの声に、静かに耳を澄ませている。",
};

export function ageBackgroundLines(age: LifeAge): SceneLine[] {
  const year = YEAR_BY_AGE[age];
  return [
    { speaker: "SYSTEM", text: `接続先を更新中…\n${year}年。ミナトは${age}歳になったよ。` },
    { speaker: "NARRATOR", text: BACKGROUND_BY_AGE[age] },
    { speaker: "SYSTEM", text: "この時代に出てきそうな制度を出すね。\nきみの直感で、ひとつ選んでみて！" },
  ];
}

export function ageYear(age: LifeAge): number {
  return YEAR_BY_AGE[age];
}
